/**
 * 東京メトロ9路線・182駅の埋め込みデータ。
 *
 * 緯度経度は可視化目的の概略値（±数百mの誤差は許容）。ロゴ・商標画像は
 * 一切使わず、路線名・駅名・ラインカラーという事実の記述のみを収録する。
 *
 * 方針:
 * - 丸ノ内線の方南町支線は収録しない（路線=1本のポリラインを保つため）
 * - 有楽町線と副都心線の和光市—小竹向原共用区間は両方に重複収録する
 *   （基準深度差で縦に分離されるので描画は干渉しない）
 * - 乗換駅はデータに持たせず、mount 時に駅名の完全一致で自動検出する
 */

export interface StationDef {
  /** 駅名（日本語） */
  name: string
  lat: number
  lng: number
  /** 深度上書き(m)。正=地下、負=地上・高架。省略時は路線の基準深度 */
  depth?: number
  /** ラベル表示レベル。1=常時表示 2=high/midで表示。省略=非表示 */
  label?: 1 | 2
}

export interface LineDef {
  id: string
  /** 路線名（日本語） */
  name: string
  /** 公式ラインカラー */
  color: string
  /** 基準深度(m)。おおよその実勢を誇張前提で */
  baseDepth: number
  /** 日中ヘッドウェイ（実時間秒） */
  headway: number
  /** 最高速度(km/h) */
  vmax: number
  stations: StationDef[]
}

